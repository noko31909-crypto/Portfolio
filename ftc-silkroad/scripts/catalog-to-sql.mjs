// Generates supabase/seed-parts.sql from site/data/parts-catalog.json, so the website
// and the database share one list of part ids.
//
//   node scripts/catalog-to-sql.mjs

import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('site/data/parts-catalog.json', root), 'utf8'));

const str = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a?.length ? `array[${a.map(str).join(', ')}]::text[]` : `'{}'::text[]`);

const ids = new Set();
const rows = catalog.parts.map((p) => {
  if (ids.has(p.id)) throw new Error(`Duplicate part id: ${p.id}`);
  ids.add(p.id);
  return `  (${[str(p.id), str(p.brand), str(p.name), str(p.sku), str(p.category), arr(p.aliases), str(p.url), str(p.image)].join(', ')})`;
});

const sql = `-- Generated by scripts/catalog-to-sql.mjs from site/data/parts-catalog.json. Do not edit by hand.
insert into parts (id, brand, name, sku, category, aliases, url, image) values
${rows.join(',\n')}
on conflict (id) do update set
  brand = excluded.brand, name = excluded.name, sku = excluded.sku,
  category = excluded.category, aliases = excluded.aliases, url = excluded.url,
  image = excluded.image;
`;

await writeFile(new URL('supabase/seed-parts.sql', root), sql);
console.log(`Wrote ${rows.length} parts to supabase/seed-parts.sql`);
